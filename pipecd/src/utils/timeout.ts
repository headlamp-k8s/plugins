/** How long a PipeCD API request may take before the page gives up on it. */
export const REQUEST_TIMEOUT_MS = 30000;

/**
 * Rejects with `message` after `ms`. Most API calls take no abort signal, so a
 * stuck one keeps running, but it can no longer keep the page busy.
 */
export function withTimeout<T>(promise: Promise<T>, ms: number, message: string): Promise<T> {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error(message)), ms);
    promise.then(
      value => {
        clearTimeout(timer);
        resolve(value);
      },
      err => {
        clearTimeout(timer);
        reject(err);
      }
    );
  });
}
